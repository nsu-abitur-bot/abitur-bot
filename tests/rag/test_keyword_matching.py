def test_search_returns_page_content_attribute():
    """Каждый результат search_similar должен иметь атрибут page_content."""
    results = search_similar("НГУ", k=3)
    assert results
    for doc in results:
        assert hasattr(doc, "page_content"), "Документ не имеет атрибута page_content"
        assert isinstance(doc.page_content, str)
        assert doc.page_content.strip(), "page_content не должен быть пустым"


def test_search_respects_k_parameter():
    """search_similar должен возвращать ровно k результатов (если в базе достаточно чанков)."""
    for k in (1, 3, 5):
        results = search_similar("факультет НГУ", k=k)
        assert len(results) == k, f"Ожидалось {k} результатов, получено {len(results)}"


def test_different_queries_return_different_top_results():
    """Разные запросы должны возвращать разные топ-чанки."""
    res_fit = search_similar("ФИТ информационные технологии", k=1)
    res_geo = search_similar("геология геофизика нефть", k=1)
    assert res_fit[0].page_content != res_geo[0].page_content, (
        "Ожидались разные топ-чанки для несвязанных запросов"
    )
